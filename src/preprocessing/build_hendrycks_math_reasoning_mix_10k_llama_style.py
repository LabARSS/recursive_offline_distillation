"""Build a Llama-style MATH mix: Llama-3.3-70B CoT, Llama 3B self chains, one OMI2 chain per question.

OpenMathInstruct-2 was generated by Llama-3.1-405B, so all three sources share
the Llama family style. All chains are verified correct against train gold,
strictly under 10,000 characters, test-decontaminated, and never truncated.
Llama 70B chains lose their trailing ``Answer: <x>`` line; OMI2 chains are kept
as-is, as in earlier mixes. Self chains include all passes (greedy plus the
t=0.7 resamples of greedy failures). OMI2 keeps one random chain per question
(seed 42) so it stays roughly a third of the mix. Answers that follow </think>
are normalized (boxed contents kept, one outer math delimiter removed).

Run from the repository root:
  PYTHONPATH=src python -m preprocessing.build_hendrycks_math_reasoning_mix_10k_llama_style
"""

import json

import pandas as pd

from .build_hendrycks_math_reasoning_mix_10k import DISTILL, ROOT, build_mix, sha256_file
from .build_hendrycks_math_reasoning_mix_10k_cot_teachers import length_stats, omi2_traces, teacher_traces
from .build_hendrycks_math_reasoning_mix_10k_qwen_style import assert_answers_verify, clean_answer, self_traces

OUTPUT = DISTILL / "hendrycks_math_reasoning_mix_under10k_llama_style.parquet"
SEED = 42


def main() -> None:
    paths = {
        "train": ROOT / "data/source/hendrycks_math/hendrycks_math_train.parquet",
        "test": ROOT / "data/source/hendrycks_math/hendrycks_math_test.parquet",
        "llama_70b": DISTILL / "hendrycks_math_distilled_cot_llama_70b.parquet",
        "self_llama_3b": DISTILL / "hendrycks_math_self_distilled_llama_3b.parquet",
        "omi2_20k": DISTILL / "hendrycks_math_openmathinstruct2_math_all2sol_aug7000.parquet",
    }
    hashes = {name: sha256_file(path) for name, path in paths.items()}
    frames = {name: pd.read_parquet(path) for name, path in paths.items()}

    sources = {
        "llama_70b": teacher_traces("llama_70b", frames["llama_70b"]),
        "self_llama_3b": self_traces(frames["self_llama_3b"], source="self_llama_3b"),
        "omi2_math": omi2_traces(frames["omi2_20k"]),
    }
    parts, audits = [], []
    for name, traces in sources.items():
        frame, audit, _ = build_mix(frames["train"], frames["test"], traces, max_chars=10000)
        if name == "omi2_math":
            kept = frame.sort_values("trace_id").groupby("question_id").sample(n=1, random_state=SEED)
            audit.loc[audit.status.eq("included") & ~audit.reasoning_sha256.isin(kept.reasoning_sha256), "status"] = "not_sampled"
            frame = kept
        print(f"{name}: {audit.status.value_counts().to_dict()}", flush=True)
        parts.append(frame)
        audits.append(audit)
    for name, path in paths.items():
        if sha256_file(path) != hashes[name]:
            raise ValueError(f"Input changed during construction: {path}")

    output = pd.concat(parts, ignore_index=True).sample(frac=1, random_state=SEED).reset_index(drop=True)
    output = output.drop_duplicates(["question_id", "reasoning_sha256"]).reset_index(drop=True)
    output["distill_answer"] = output.distill_answer.map(clean_answer)
    assert_answers_verify(output)
    output["original_question_id"] = output.question_id
    output["question_id"] = [f"math_llama_style_{i:06d}" for i in range(len(output))]
    assert output.trace_id.is_unique and output.distill_reasoning.str.len().lt(10000).all()
    teachers = output[output.source == "llama_70b"]
    assert not teachers.distill_reasoning.str.contains(r"\nAnswer:[^\n]*$", regex=True).any()
    assert output[output.source == "omi2_math"].original_question_id.is_unique

    manifest = {
        "rows": len(output), "unique_questions": output.original_question_id.nunique(),
        **length_stats(output.reasoning_chars),
        "max_reasoning_chars_exclusive": 10000, "traces_truncated": 0,
        "omi2_sampling": {"chains_per_question": 1, "seed": SEED},
        "self_passes": frames["self_llama_3b"]["pass"].value_counts().to_dict(),
        "correctness": "final-answer verification against train gold (OMI2 and self chains also require their source flag)",
        "teacher_reasoning": "Llama 70B CoT response with its trailing 'Answer: <x>' line removed; OMI2 chains unchanged",
        "decontamination": "exact match or shared 13-word sequence with all 5,000 MATH test questions",
        "question_ids": "unique per row; original_question_id retains question grouping only",
        "sources": {
            source: {"traces": len(rows), "unique_questions": rows.original_question_id.nunique(), **length_stats(rows.reasoning_chars)}
            for source, rows in output.groupby("source")
        },
        "chains_per_question": {str(k): int(v) for k, v in output.groupby("original_question_id").size().value_counts().sort_index().items()},
        "input_files": {name: {"path": str(path.relative_to(ROOT)), "sha256": hashes[name]} for name, path in paths.items()},
    }
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    output.to_parquet(OUTPUT, index=False)
    pd.concat(audits, ignore_index=True).to_parquet(OUTPUT.with_suffix(".audit.parquet"), index=False)
    manifest["output_sha256"] = sha256_file(OUTPUT)
    OUTPUT.with_suffix(".manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(json.dumps({k: manifest[k] for k in ("rows", "unique_questions", "median_chars", "p95_chars", "sources", "chains_per_question")}, indent=2))
    print(f"Saved {OUTPUT}", flush=True)


if __name__ == "__main__":
    main()
