"""
Download the train_1M split of nvidia/OpenMathInstruct-2 and save a random
subset of its MATH-derived problems as a distillation artifact compatible with
HendrycksMathReasoningResponseDataset.

Usage:
  python src/preprocessing/download_openmathinstruct2.py

Outputs:
  data/out/distillation/hendrycks_math_openmathinstruct2_math5000_aug5000.parquet

Solutions were generated by Llama-3.1-405B-Instruct. GSM8K-derived problems are
dropped, and only one solution is kept per problem so the subset covers as many
distinct problems as possible. Problems that match a Hendrycks MATH test question
exactly or share a 13-word n-gram with one are removed before sampling.
"""

import re
from pathlib import Path

import pandas as pd
from datasets import load_dataset

DATASET_ID = "nvidia/OpenMathInstruct-2"
SPLIT = "train_1M"
ROWS_PER_SOURCE = {"math": 5000, "augmented_math": 5000}
SEED = 42
NGRAM_SIZE = 13
ROOT = Path(__file__).resolve().parents[2]
TEST_PATH = ROOT / "data/source/hendrycks_math/hendrycks_math_test.parquet"
OUTPUT_PATH = ROOT / "data/out/distillation/hendrycks_math_openmathinstruct2_math5000_aug5000.parquet"


def normalize(text: str) -> str:
    return re.sub(r"\s+", " ", text).strip().lower()


def ngrams(text: str) -> set[tuple[str, ...]]:
    """Word n-grams of a normalized question; short questions yield themselves."""
    words = text.split(" ")
    if len(words) < NGRAM_SIZE:
        return {tuple(words)}
    return {tuple(words[i : i + NGRAM_SIZE]) for i in range(len(words) - NGRAM_SIZE + 1)}


def main():
    test_questions = {normalize(q) for q in pd.read_parquet(TEST_PATH)["question"]}
    test_ngrams = set().union(*(ngrams(q) for q in test_questions))
    short_test_questions = {q for q in test_questions if len(q.split(" ")) < NGRAM_SIZE}

    # Only download train_1M; skip checking for the card's other (much larger) splits.
    ds = load_dataset(
        DATASET_ID, data_files={SPLIT: f"data/{SPLIT}-*.parquet"}, split=SPLIT, verification_mode="no_checks"
    )
    print(f"Downloaded {len(ds)} rows from {DATASET_ID}/{SPLIT}")

    df = ds.to_pandas()
    df = df[df["problem_source"].isin(ROWS_PER_SOURCE)]
    df = df[
        df["expected_answer"].str.strip().astype(bool)
        & df["generated_solution"].str.contains(r"\boxed", regex=False)
    ]
    df = df.sample(frac=1, random_state=SEED).drop_duplicates("problem")

    normalized = df["problem"].map(normalize)
    exact = normalized.isin(test_questions)
    near = normalized.map(lambda q: q in short_test_questions or not ngrams(q).isdisjoint(test_ngrams))
    contaminated = exact | near
    for source in ROWS_PER_SOURCE:
        in_source = df["problem_source"] == source
        print(
            f"{source}: dropped {int((exact & in_source).sum())} exact and "
            f"{int((near & ~exact & in_source).sum())} near-duplicate test matches "
            f"out of {int(in_source.sum())} unique problems"
        )
    df = df[~contaminated]

    subsets = []
    for source, n_rows in ROWS_PER_SOURCE.items():
        source_df = df[df["problem_source"] == source]
        if len(source_df) < n_rows:
            raise ValueError(f"Only {len(source_df)} clean unique problems for {source}, need {n_rows}")
        subsets.append(source_df.head(n_rows))
    df = pd.concat(subsets).sample(frac=1, random_state=SEED)
    assert not df["problem"].map(normalize).isin(test_questions).any(), "Subset contains a test question"
    print(f"Sampled {len(df)} rows; sources: {df['problem_source'].value_counts().to_dict()}")

    out = pd.DataFrame(
        {
            "question": df["problem"].values,
            "answer": df["expected_answer"].str.strip().values,
            "answer_w_steps": df["generated_solution"].values,
            "question_id": [str(i) for i in range(len(df))],
            "distill_ans_correct": True,
            "distill_reasoning": df["generated_solution"].str.strip().values,
            "distill_answer": df["expected_answer"].str.strip().values,
            "problem_source": df["problem_source"].values,
        }
    )
    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    out.to_parquet(OUTPUT_PATH, index=False)

    print(f"Saved {len(out)} rows to {OUTPUT_PATH}")
    print(f"Columns: {list(out.columns)}")
    print(out.head(2).to_string())


if __name__ == "__main__":
    main()
